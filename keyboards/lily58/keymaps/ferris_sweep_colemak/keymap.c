/* Converted from a Ferris Sweep (34-key) ZMK config:
 * https://github.com/ahmadkarlam/zmk-config/blob/main/config/cradio.keymap
 *
 * The Ferris Sweep uses 3 rows x 5 cols per hand + 2 thumb keys per hand.
 * Lily58 has 4 rows x 6 cols per hand + 4 thumb keys per hand, so:
 *   - The top row (numbers/Esc) is unused -> KC_NO on every layer.
 *   - The outermost pinky column on each hand is unused -> KC_NO.
 *   - The 2 extra keys next to the bottom row are unused -> KC_NO.
 *   - Only the innermost 2 of the 4 thumb keys per hand are used;
 *     the outer 2 thumb keys per hand -> KC_NO.
 */

